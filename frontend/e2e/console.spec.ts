import { test, expect, type Page } from '@playwright/test'
async function fillProxy(page: Page, name: string, port: string) {
  await page.getByRole('textbox', { name: '代理名称', exact: true }).fill(name)
  await page.getByRole('textbox', { name: '本地地址', exact: true }).fill('127.0.0.1')
  await page.getByLabel('本地端口', { exact: true }).fill('8080')
  await page.getByLabel('远程端口', { exact: true }).fill(port)
  await page.getByRole('textbox', { name: '显示名称', exact: true }).fill('测试服务')
}
