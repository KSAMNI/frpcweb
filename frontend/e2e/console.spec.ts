test('concurrent edits reject stale saves and preserve the entered values', async ({ page, context }) => {
  await page.goto('/config')
  await page
    .locator('tr')
    .filter({ hasText: 'nas-web' })
    .getByRole('button', { name: '编辑', exact: true })
    .click()
  await page.getByRole('textbox', { name: '显示名称', exact: true }).fill('尚未保存的编辑')
  const other = await context.newPage()
  await other.goto('/settings')
  await other.getByRole('textbox', { name: '目标地址' }).fill('updated.example.com')
  await other.getByRole('button', { name: '保存地址', exact: true }).click()
  await expect(other.getByText('访问地址已保存，无需重启 frpc')).toBeVisible()
  await page.getByRole('button', { name: '保存配置', exact: true }).last().click()
  await expect(page.getByText(/配置已被其他页面或程序修改/)).toBeVisible()
  await expect(page.getByRole('textbox', { name: '显示名称', exact: true })).toHaveValue('尚未保存的编辑')
  await other.close()
})
