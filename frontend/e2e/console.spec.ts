test('launcher is local-only, searchable and protocol-aware', async ({ page }, info) => {
  const external: string[] = []
  const errors: string[] = []
  page.on('request', (r) => {
    if (!r.url().startsWith('http://127.0.0.1:18080')) external.push(r.url())
  })
  page.on('pageerror', (e) => errors.push(e.message))
  await page.goto('/')
  await expect(page.locator('.service-card')).toHaveCount(6)
  await expect(
    page.locator('.service-card').filter({ hasText: '游戏服务器' }).getByRole('link', { name: '打开服务' }),
  ).toHaveCount(0)
  await expect(
    page.locator('.service-card').filter({ hasText: '代码仓库' }).getByRole('link', { name: '打开服务' }),
  ).toHaveAttribute('href', 'https://git.example.com/')
  await page.screenshot({ path: info.outputPath('home-desktop.png'), fullPage: true })
  await page.getByRole('textbox', { name: '搜索服务' }).fill('开发服务器')
  await expect(page.locator('.service-card')).toHaveCount(1)
  await page.getByRole('textbox', { name: '搜索服务' }).fill('')
  await page.getByRole('button', { name: '只看收藏' }).click()
  await expect(page.locator('.service-card')).toHaveCount(2)
  expect(external).toEqual([])
  expect(errors).toEqual([])
})
test('CRUD and validation do not reload the document', async ({ page }, info) => {
  await page.goto('/config')
  await expect(page.getByRole('button', { name: '新增代理', exact: true })).toBeVisible()
  const timeOrigin = await page.evaluate(() => performance.timeOrigin)
  await page.screenshot({ path: info.outputPath('proxies-desktop.png'), fullPage: true })
  await page.getByRole('button', { name: '新增代理', exact: true }).click()
  await page.getByRole('button', { name: '保存配置', exact: true }).last().click()
  await expect(page.getByText('请填写代理名称', { exact: true })).toBeVisible()
  await fillProxy(page, 'e2e-service', '18888')
  await page.getByRole('textbox', { name: '分组', exact: true }).fill('本地测试')
  await page.screenshot({ path: info.outputPath('proxy-drawer.png'), fullPage: true })
  await page.getByRole('button', { name: '保存配置', exact: true }).last().click()
  await expect(page.locator('.n-drawer')).toHaveCount(0)
  let row = page.locator('tr').filter({ hasText: 'e2e-service' })
  await expect(row).toHaveCount(1)
  await row.getByRole('button', { name: '编辑', exact: true }).click()
  await page.getByRole('textbox', { name: '显示名称', exact: true }).fill('编辑后的服务')
  await page.getByRole('button', { name: '保存配置', exact: true }).last().click()
  await expect(row).toContainText('编辑后的服务')
  await row.getByRole('button', { name: '复制', exact: true }).click()
  await expect(page.getByRole('textbox', { name: '代理名称', exact: true })).toHaveValue('e2e-service-copy')
  await page.getByLabel('远程端口', { exact: true }).fill('18889')
  await page.getByRole('button', { name: '保存配置', exact: true }).last().click()
  await expect(page.locator('tr').filter({ hasText: 'e2e-service-copy' })).toHaveCount(1)
  await page.getByRole('button', { name: '新增代理', exact: true }).click()
  await fillProxy(page, 'e2e-service', '18890')
  await page.getByRole('button', { name: '保存配置', exact: true }).last().click()
  await expect(page.getByText('请使用不同的代理名称')).toBeVisible()
  await page.getByRole('button', { name: '关闭编辑抽屉' }).click()
  await page.getByRole('button', { name: '放弃修改', exact: true }).click()
  row = page.locator('tr').filter({ hasText: 'e2e-service-copy' })
  await row.getByRole('button', { name: '删除', exact: true }).click()
  await page.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(row).toHaveCount(0)
  expect(await page.evaluate(() => performance.timeOrigin)).toBe(timeOrigin)
})
